import { CreateUserDto } from '@/modules/users/dto/user.dto';
import {
  IsEmail,
  IsString,
  MinLength,
  MaxLength,
  IsNotEmpty,
  IsOptional,
  IsBoolean,
  Matches,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class StudentRegisterDto extends CreateUserDto {
  @ApiPropertyOptional({
    example: 'b1f4c2d0-8a71-4f2e-b6a1-3c9f7d5e2a10',
    description: 'Stable per-device identifier generated by the client',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceId?: string;

  @ApiPropertyOptional({
    example: 'Chrome on Windows',
    description: 'Human readable device/browser name',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceName?: string;

  @ApiPropertyOptional({
    example: 'web',
    description: 'Client platform (web, android, ios, desktop)',
  })
  @IsOptional()
  @IsString()
  @MaxLength(50)
  platform?: string;
}

export class StudentLoginDto {
  @ApiProperty({
    example: 'rahul.kumar@email.com',
    description: 'Registered email address',
  })
  @IsEmail({}, { message: 'Please provide a valid email address' })
  email: string;

  @ApiProperty({ example: 'Rahul@123', description: 'Account password' })
  @IsString()
  @MinLength(8)
  @MaxLength(50)
  password: string;

  @ApiPropertyOptional({
    example: 'b1f4c2d0-8a71-4f2e-b6a1-3c9f7d5e2a10',
    description:
      'Stable per-device identifier generated by the client and stored locally. Recommended for reliable device detection.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceId?: string;

  @ApiPropertyOptional({
    example: 'Chrome on Windows',
    description: 'Human readable device/browser name shown in login alerts',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceName?: string;

  @ApiPropertyOptional({
    example: 'web',
    description: 'Client platform (web, android, ios, desktop)',
  })
  @IsOptional()
  @IsString()
  @MaxLength(50)
  platform?: string;

  @ApiPropertyOptional({
    example: false,
    description:
      'Set to true after the user confirms "log out other devices". Revokes the other active session and logs this device in.',
  })
  @IsOptional()
  @IsBoolean()
  logoutOtherDevices?: boolean;
}

/**
 * Exchanges the short-lived approval token from an ALREADY_LOGGED_IN conflict
 * for a real session, signing the previously active device out.
 */
export class ApproveDeviceLoginDto {
  @ApiProperty({
    description:
      'Short-lived approval token returned with the 409 ALREADY_LOGGED_IN login response',
  })
  @IsString()
  @IsNotEmpty({ message: 'Approval token is required' })
  approvalToken: string;

  @ApiPropertyOptional({
    example: 'b1f4c2d0-8a71-4f2e-b6a1-3c9f7d5e2a10',
    description:
      'Stable per-device identifier; must match the device that requested the approval',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceId?: string;

  @ApiPropertyOptional({
    example: 'Chrome on Windows',
    description: 'Human readable device/browser name',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  deviceName?: string;

  @ApiPropertyOptional({
    example: 'web',
    description: 'Client platform (web, android, ios, desktop)',
  })
  @IsOptional()
  @IsString()
  @MaxLength(50)
  platform?: string;
}

export class RefreshTokenDto {
  @ApiProperty({
    example: 'eyJhbGciOiJIUzI1NiIs...',
    description: 'Refresh token from login response',
  })
  @IsString()
  @IsNotEmpty({ message: 'Refresh token is required' })
  refreshToken: string;
}

export class ForgotPasswordDto {
  @ApiProperty({
    example: 'admin@techng.in',
    description: 'Email address of the account to recover',
  })
  @IsEmail({}, { message: 'Please provide a valid email address' })
  email: string;
}

export class ResetPasswordDto {
  @ApiProperty({
    description: 'Single-use token from the password reset email',
  })
  @IsString()
  @IsNotEmpty({ message: 'Reset token is required' })
  token: string;

  @ApiProperty({
    example: 'NewStrongPass@123',
    description: 'New account password',
  })
  @IsString()
  @MinLength(8, { message: 'Password must be at least 8 characters long' })
  @MaxLength(50)
  newPassword: string;
}

/** Student password reset with the same strength rules as registration. */
export class StudentResetPasswordDto extends ResetPasswordDto {
  @ApiProperty({
    example: 'NewStrongPass@123',
    description:
      'New password - min 8 chars, 1 uppercase, 1 number, 1 special char',
  })
  @IsString()
  @MinLength(8, { message: 'Password must be at least 8 characters long' })
  @MaxLength(50)
  @Matches(/^(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]+$/, {
    message:
      'Password must contain at least 1 uppercase letter, 1 number, and 1 special character',
  })
  declare newPassword: string;
}
